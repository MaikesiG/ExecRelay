import type { TerminalTab, TerminalTabColorKey } from './types';

export const DEFAULT_TERMINAL_TAB_BASE_NAME = 'Terminal';
export const MAX_TERMINAL_TAB_BASE_NAME_LENGTH = 40;
export const TERMINAL_TAB_COLOR_KEYS: readonly TerminalTabColorKey[] = [
  'emerald',
  'blue',
  'violet',
  'amber',
  'cyan',
  'rose',
] as const;

/**
 * Normalizes the user-owned portion of a terminal tab name. Positional suffixes
 * are deliberately excluded from this value and are added only for display.
 */
export function normalizeTerminalTabBaseName(
  value: string | null | undefined,
): string {
  const trimmed = value?.trim() ?? '';
  return (
    trimmed.slice(0, MAX_TERMINAL_TAB_BASE_NAME_LENGTH) ||
    DEFAULT_TERMINAL_TAB_BASE_NAME
  );
}

/**
 * Migrates only the legacy default pattern, whose numeric suffix is known to
 * have been generated by ExecRelay. Custom names ending in numbers are kept.
 */
export function migrateLegacyTerminalTabBaseName(
  value: string | null | undefined,
): string {
  const normalized = normalizeTerminalTabBaseName(value);
  return /^Terminal \d+$/.test(normalized)
    ? DEFAULT_TERMINAL_TAB_BASE_NAME
    : normalized;
}

export function getTerminalTabBaseName(tab: TerminalTab): string {
  if (typeof tab.baseName === 'string' && tab.baseName.trim().length > 0) {
    return normalizeTerminalTabBaseName(tab.baseName);
  }

  return migrateLegacyTerminalTabBaseName(tab.name ?? tab.label);
}

/** The single canonical terminal-tab display-name formatter. */
export function getTerminalTabDisplayName(tab: TerminalTab): string {
  return getTerminalTabBaseName(tab);
}

export function isTerminalTabColorKey(
  value: unknown,
): value is TerminalTabColorKey {
  return TERMINAL_TAB_COLOR_KEYS.includes(value as TerminalTabColorKey);
}

function getColorIndexFromTabId(tabId: string): number {
  let hash = 0;
  for (let index = 0; index < tabId.length; index += 1) {
    hash = (hash * 31 + tabId.charCodeAt(index)) >>> 0;
  }
  return hash % TERMINAL_TAB_COLOR_KEYS.length;
}

export function getTerminalTabColorKey(tab: TerminalTab): TerminalTabColorKey {
  return isTerminalTabColorKey(tab.colorKey)
    ? tab.colorKey
    : TERMINAL_TAB_COLOR_KEYS[getColorIndexFromTabId(tab.id)];
}

export function getNextTerminalTabColorKey(
  tabs: ReadonlyArray<TerminalTab>,
): TerminalTabColorKey {
  const usedColors = new Set(tabs.map(getTerminalTabColorKey));
  const unusedColor = TERMINAL_TAB_COLOR_KEYS.find(
    (colorKey) => !usedColors.has(colorKey),
  );
  return unusedColor ?? TERMINAL_TAB_COLOR_KEYS[tabs.length % TERMINAL_TAB_COLOR_KEYS.length];
}

export function getTerminalTabColorCssValue(
  colorKey: TerminalTabColorKey,
): string {
  return `var(--terminal-tab-color-${colorKey})`;
}
